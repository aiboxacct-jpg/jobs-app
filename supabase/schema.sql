-- Jobs app schema — run once in the Supabase project's SQL editor.
-- Data access is server-side only (service-role key); RLS is enabled with
-- NO policies, so the anon/public API can read or write nothing directly.

create table if not exists public.jobs (
  id bigint generated by default as identity primary key,
  url text unique not null,
  title text,
  company text,
  company_about text,
  description text,
  why_fit text,
  location text,
  work_mode text,
  salary text,
  posted_date date,
  found_date date,
  source text,
  status text not null default 'New',
  applied_date date,
  apply_requested boolean not null default false,
  apply_requested_at timestamptz,
  apply_acknowledged boolean not null default false,
  documents jsonb not null default '[]'::jsonb,
  match_score int,
  match_reasons text,
  apply_later boolean not null default false,
  easy_apply boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists jobs_status_idx on public.jobs (status);
create index if not exists jobs_apply_pending_idx
  on public.jobs (apply_requested, apply_acknowledged);

alter table public.jobs enable row level security;
-- Deliberately no policies: only the service-role key (server-side) can
-- touch this table. The browser never talks to PostgREST directly.

create or replace function public.jobs_touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists jobs_touch on public.jobs;
create trigger jobs_touch
  before update on public.jobs
  for each row execute function public.jobs_touch_updated_at();

